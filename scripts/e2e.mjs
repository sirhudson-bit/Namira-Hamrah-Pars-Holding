import { PrismaClient } from "@prisma/client";
import { unlink } from "node:fs/promises";
import path from "node:path";

const BASE = process.env.E2E_BASE ?? "http://localhost:3210";
const prisma = new PrismaClient();
let pass = 0;
let fail = 0;

function check(label, ok, detail = "") {
  if (ok) {
    pass += 1;
    console.log(`  OK   ${label}${detail ? ` — ${detail}` : ""}`);
  } else {
    fail += 1;
    console.log(`  FAIL ${label}${detail ? ` — ${detail}` : ""}`);
  }
}

/** Pulls the hidden server-action inputs out of a form fragment. */
function actionFields(fragment) {
  const fields = [];
  const re = /<input type="hidden" name="(\$ACTION[^"]*)"(?: value="([^"]*)")?\/>/g;
  let m;
  while ((m = re.exec(fragment)) !== null) {
    fields.push([
      m[1],
      (m[2] ?? "")
        .replace(/&quot;/g, '"')
        .replace(/&amp;/g, "&")
        .replace(/&lt;/g, "<")
        .replace(/&gt;/g, ">")
        .replace(/&#39;/g, "'"),
    ]);
  }
  return fields;
}

/**
 * Action fields for the first <form> on a page, or — when `match` is given — for
 * the first form whose markup matches. A page can carry several forms (the admin
 * topbar renders a logout form before the page's own forms), so callers that
 * need a specific one must say so.
 */
function extractActionFields(html, match) {
  const forms = html.match(/<form[^>]*>[\s\S]*?<\/form>/g) ?? [];
  const target = (match && forms.find((f) => match.test(f))) || forms[0] || "";
  return actionFields(target);
}

function buildBody(fields, extra) {
  const body = new FormData();
  for (const [k, v] of fields) body.append(k, v);
  for (const [k, v] of Object.entries(extra)) body.append(k, v);
  return body;
}

async function main() {
  console.log(`E2E against ${BASE}\n`);
  const marker = `E2E-${Date.now()}`;
  const subscriberEmail = `e2e-${Date.now()}@example.com`;

  /*
    A real PNG, generated by sharp. The hand-rolled 1×1 fixture this suite used
    before is rejected by libpng ("read error"), which would make the WebP
    conversion look broken when it is the fixture that is malformed.
  */
  const sharpMod = (await import("sharp")).default;
  const PNG = await sharpMod({
    create: {
      width: 24,
      height: 24,
      channels: 4,
      background: { r: 15, g: 124, b: 113, alpha: 1 },
    },
  })
    .png()
    .toBuffer();
  let uploadedLogoPath = null;

  // ---------- login ----------
  console.log("login (wrong password):");
  const loginFields = extractActionFields(await (await fetch(`${BASE}/admin/login`)).text());
  check("login form exposes action fields", loginFields.length >= 3, `${loginFields.length} fields`);
  const bad = await fetch(`${BASE}/admin/login`, {
    method: "POST",
    body: buildBody(loginFields, { email: "admin@namiragroup.ir", password: "definitely-wrong" }),
    redirect: "manual",
  });
  check("wrong password rejected (no session cookie)", !bad.headers.get("set-cookie"));

  console.log("\nlogin (correct password):");
  const good = await fetch(`${BASE}/admin/login`, {
    method: "POST",
    body: buildBody(loginFields, { email: "admin@namiragroup.ir", password: "NamiraAdmin!2026" }),
    redirect: "manual",
  });
  const cookie = (good.headers.get("set-cookie") ?? "").split(";")[0];
  check("session cookie issued", cookie.includes("namira_admin="));
  check("login redirects (3xx)", good.status >= 300 && good.status < 400, `status ${good.status}`);

  console.log("\nauthenticated access:");
  const dash = await fetch(`${BASE}/admin/dashboard`, { headers: { cookie }, redirect: "manual" });
  check("dashboard reachable with login cookie", dash.status === 200, `status ${dash.status}`);

  // ---------- admin edit forms are populated ----------
  // Regression guard: the edit forms were once rendered from a static field
  // list, so every record opened blank and saving it overwrote the row.
  console.log("\nadmin edit forms:");
  const groupsAdmin = await (await fetch(`${BASE}/admin/business-groups`, { headers: { cookie } })).text();
  check(
    "group edit form carries the record's slug",
    groupsAdmin.includes('name="slug"') && /value="digital"/.test(groupsAdmin),
  );
  check(
    "group edit form carries the record's name",
    /value="گروه دیجیتال"/.test(groupsAdmin),
  );
  const pagesAdmin = await (await fetch(`${BASE}/admin/pages`, { headers: { cookie } })).text();
  check(
    "page editor lists every top-level route",
    pagesAdmin.includes("/business-groups") && pagesAdmin.includes("صفحات اصلی"),
  );
  check(
    "page editor ships the content toolbar",
    pagesAdmin.includes("پیش‌نمایش") && pagesAdmin.includes("کتابخانه رسانه"),
  );

  // ---------- public pages ----------
  console.log("\npublic pages:");
  const home = await (await fetch(`${BASE}/`)).text();
  check(
    "home renders the hero orb wrapper",
    // The particle scene is WebGL and therefore client-only, so only the
    // wrapper and its static fallback are expected in the server HTML.
    home.includes('class="sphere"'),
  );
  check(
    "home still renders the Labs WebGL fallback (client-only scene)",
    home.includes("animate-soft-pulse") && home.includes("نامیرا لبز"),
  );
  check(
    "home renders the ambient-grid canvas server-side",
    // Matches on the canvas + its pointer-events class rather than an exact
    // class string, so reordering/renaming z-index utilities cannot break it.
    /<canvas[^>]*class="[^"]*pointer-events-none/.test(home),
  );
  check("home is RTL", home.includes('dir="rtl"'));
  check("home ships the built-in app icon", home.includes("icon.svg"));

  // ---------- contact form ----------
  console.log("\ncontact form:");
  const contactFields = extractActionFields(await (await fetch(`${BASE}/contact`)).text());
  const contact = await fetch(`${BASE}/contact`, {
    method: "POST",
    body: buildBody(contactFields, {
      name: "آزمون خودکار",
      email: "e2e@example.com",
      message: `این یک پیام آزمایشی خودکار است ${marker}`,
      consent: "on",
    }),
    redirect: "manual",
  });
  check("contact action responds", contact.status === 200, `status ${contact.status}`);
  check(
    "contact message persisted",
    Boolean(await prisma.contactMessage.findFirst({ where: { message: { contains: marker } } })),
  );

  const invalid = await fetch(`${BASE}/contact`, {
    method: "POST",
    body: buildBody(contactFields, { name: "ب", email: "nope", message: "کوتاه", consent: "on" }),
    redirect: "manual",
  });
  check("invalid contact submission rejected", (await invalid.text()).includes("ایمیل معتبر نیست"));

  // ---------- newsletter ----------
  console.log("\nnewsletter:");
  const nlFields = extractActionFields(await (await fetch(`${BASE}/`)).text());
  const sub = await fetch(`${BASE}/`, {
    method: "POST",
    body: buildBody(nlFields, { email: subscriberEmail, consent: "on" }),
    redirect: "manual",
  });
  check("newsletter action responds", sub.status === 200, `status ${sub.status}`);
  check(
    "subscriber persisted",
    Boolean(await prisma.newsletterSubscriber.findUnique({ where: { email: subscriberEmail } })),
  );

  // ---------- branding upload (logo) ----------
  console.log("\nbranding upload:");
  const settingsHtml = await (
    await fetch(`${BASE}/admin/settings`, { headers: { cookie } })
  ).text();
  check("settings exposes a branding uploader", settingsHtml.includes("لوگوی اصلی"));
  // Target the logo uploader specifically (value="logo", not "logo_light").
  const brandFields = extractActionFields(settingsHtml, /value="logo"/);
  const fd = new FormData();
  for (const [k, v] of brandFields) fd.append(k, v);
  fd.append("kind", "logo");
  fd.append("file", new Blob([PNG], { type: "image/png" }), "logo.png");
  const up = await fetch(`${BASE}/admin/settings`, {
    method: "POST",
    body: fd,
    headers: { cookie },
    redirect: "manual",
  });
  check("branding upload responds", up.status === 200, `status ${up.status}`);

  const logoSetting = await prisma.setting.findUnique({ where: { key: "logo_path" } });
  uploadedLogoPath = logoSetting?.value ?? null;
  check(
    "logo_path persisted under /uploads/branding",
    Boolean(uploadedLogoPath?.startsWith("/uploads/branding/")),
    uploadedLogoPath ?? "(empty)",
  );

  check(
    "branding upload is stored as WebP",
    Boolean(uploadedLogoPath?.endsWith(".webp")),
    uploadedLogoPath ?? "(empty)",
  );

  if (uploadedLogoPath) {
    const homeAfter = await (await fetch(`${BASE}/`)).text();
    check("header renders the uploaded logo", homeAfter.includes(uploadedLogoPath));

    // Regression guard: `next start` does not serve files written to public/
    // after the build, so uploads are served through the /uploads route. If
    // this 404s, the logo and favicon silently stop appearing.
    const asset = await fetch(`${BASE}${uploadedLogoPath}`);
    check(
      "uploaded brand asset is actually served",
      asset.status === 200,
      `status ${asset.status}`,
    );
  }

  // ---------- media upload is converted to WebP ----------
  console.log("\nmedia upload:");
  const mediaPage = await (await fetch(`${BASE}/admin/media`, { headers: { cookie } })).text();
  const mediaFields = extractActionFields(mediaPage, /type="file"/);
  const mediaUp = await fetch(`${BASE}/admin/media`, {
    method: "POST",
    headers: { cookie },
    body: buildBody(mediaFields, {
      file: new File([PNG], "e2e-png.png", { type: "image/png" }),
      alt: marker,
    }),
    redirect: "manual",
  });
  check("media upload responds", mediaUp.status === 200, `status ${mediaUp.status}`);
  const mediaAsset = await prisma.mediaAsset.findFirst({ where: { alt: marker } });
  check(
    "a PNG upload is stored as WebP",
    Boolean(mediaAsset?.path.endsWith(".webp")),
    mediaAsset?.path ?? "(none)",
  );
  if (mediaAsset) {
    const served = await fetch(`${BASE}${mediaAsset.path}`);
    check(
      "the converted WebP is served",
      served.status === 200 && served.headers.get("content-type")?.includes("image/webp") === true,
      `status ${served.status}, ${served.headers.get("content-type")}`,
    );
  }

  // ---------- header logo size is admin-adjustable ----------
  console.log("\nlogo size:");
  const settingsPage = await (await fetch(`${BASE}/admin/settings`, { headers: { cookie } })).text();
  const logoFields = extractActionFields(settingsPage, /name="logo_height"/);
  const logoUp = await fetch(`${BASE}/admin/settings`, {
    method: "POST",
    headers: { cookie },
    body: buildBody(logoFields, { logo_height: "68" }),
    redirect: "manual",
  });
  check("logo size form responds", logoUp.status === 200, `status ${logoUp.status}`);
  const logoHeightSetting = await prisma.setting.findUnique({ where: { key: "logo_height" } });
  check("logo height persisted", logoHeightSetting?.value === "68", logoHeightSetting?.value ?? "(none)");
  const homeWithLogo = await (await fetch(`${BASE}/`)).text();
  check("header applies the configured logo height", /height:\s*68px/.test(homeWithLogo));
  // Restore so repeated runs stay comparable.
  await fetch(`${BASE}/admin/settings`, {
    method: "POST",
    headers: { cookie },
    body: buildBody(logoFields, { logo_height: "44" }),
    redirect: "manual",
  });

  // Regression guard: server actions default to a 1 MB body cap. Uploads larger
  // than that were rejected at the transport layer with a 500 before the action
  // could validate or explain — the branding uploader advertises 2 MB, so this
  // asserts a >1 MB upload actually reaches the action.
  const bigSettings = await (
    await fetch(`${BASE}/admin/settings`, { headers: { cookie } })
  ).text();
  const bigFields = extractActionFields(bigSettings, /name="kind"(?![^>]*logo)[^>]*value="favicon"/);
  const bigFile = new File([new Uint8Array(1_400_000)], "big-favicon.svg", {
    type: "image/svg+xml",
  });
  const bigUp = await fetch(`${BASE}/admin/settings`, {
    method: "POST",
    headers: { cookie },
    body: buildBody(bigFields, { kind: "favicon", file: bigFile }),
    redirect: "manual",
  });
  check(
    "a >1 MB upload clears the server-action body limit",
    bigUp.status !== 500,
    `status ${bigUp.status}`,
  );
  const faviconSetting = await prisma.setting.findUnique({ where: { key: "favicon_path" } });
  check(
    "favicon_path persisted",
    Boolean(faviconSetting?.value?.startsWith("/uploads/branding/")),
    faviconSetting?.value || "(empty)",
  );

  // ---------- cleanup ----------
  console.log("\ncleanup:");
  const delMsg = await prisma.contactMessage.deleteMany({
    where: { message: { contains: marker } },
  });
  const delSub = await prisma.newsletterSubscriber.deleteMany({ where: { email: subscriberEmail } });
  let delFile = 0;
  if (uploadedLogoPath?.startsWith("/uploads/branding/")) {
    const abs = path.join(process.cwd(), "public", uploadedLogoPath.replace(/^\//, ""));
    await unlink(abs).catch(() => {});
    delFile = 1;
    await prisma.setting.update({ where: { key: "logo_path" }, data: { value: "" } });
  }
  const faviconPath = (await prisma.setting.findUnique({ where: { key: "favicon_path" } }))?.value;
  if (faviconPath?.startsWith("/uploads/branding/")) {
    const abs = path.join(process.cwd(), "public", faviconPath.replace(/^\//, ""));
    await unlink(abs).catch(() => {});
    delFile += 1;
    await prisma.setting.update({ where: { key: "favicon_path" }, data: { value: "" } });
  }
  if (mediaAsset) {
    const abs = path.join(process.cwd(), "public", mediaAsset.path.replace(/^\//, ""));
    await unlink(abs).catch(() => {});
    await prisma.mediaAsset.delete({ where: { id: mediaAsset.id } });
    delFile += 1;
  }
  console.log(
    `  removed ${delMsg.count} message(s), ${delSub.count} subscriber(s), ${delFile} brand file(s)`,
  );

  console.log(`\n${pass} passed, ${fail} failed`);
  if (fail > 0) process.exitCode = 1;
}

main()
  .catch((e) => {
    console.error(e);
    process.exitCode = 1;
  })
  .finally(() => prisma.$disconnect());
